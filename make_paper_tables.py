r"""Generate every numeric table the paper uses, from frozen artifacts only.

⛔ No number in the paper is typed by hand. This script reads the frozen
artifacts and writes `TABLES_GENERATED.md`; the prose cites those tables.

    python make_paper_tables.py
"""
import collections
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(HERE, "TABLES_GENERATED.md")


def j(name):
    p = os.path.join(ROOT, name)
    return json.load(open(p, encoding="utf-8")) if os.path.isfile(p) else {}


L = []
W = L.append

q5 = j("Q5_RESULTS.json")
cal = j("Q5_CALIBRATION.json")
fuzz = j("Q5_FUZZ.json")
man = j("PUBLICATION_MANIFEST.json")
g2 = j("gate2_matrix.json")

ENC = ["ecapa", "redimnet_M_vb2_ptn", "redimnet_b6_lm"]
arms = sorted(q5.get("arms", {}))

W("# GENERATED TABLES — every value read from a frozen artifact\n")
W("Generated by `paper/make_paper_tables.py`. Publication manifest "
  "`%s`.\n" % str(man.get("manifest_sha256", "?"))[:16])

# ---------------------------------------------------------------- T1 panel
W("## T1 — The speaker-encoder panel (Q5)\n")
W("| slot | encoder | training corpus | device | frozen-study EER (pooled expressive) |")
W("|---|---|---|---|---|")
eers = {"redimnet_M_vb2_ptn": "0.047 [0.024, 0.072]",
        "ecapa": "0.146 [0.092, 0.177]",
        "redimnet_b6_lm": "0.064 [0.034, 0.082]"}
# Q5_SPEC §2 slot order: E1 = lowest frozen expressive EER, E2 = ECAPA fixed by
# name for continuity, E3 = the mechanical fallback. NOT the ENC list order.
SLOTS = [("E1", "redimnet_M_vb2_ptn"), ("E2", "ecapa"), ("E3", "redimnet_b6_lm")]
for slot, e in SLOTS:
    m = cal.get("panel", {}).get(e, {})
    W("| %s | `%s` | %s | %s | %s |"
      % (slot, e, m.get("training_corpus", "?"), m.get("device", "?"), eers[e]))
W("")

# ---------------------------------------------------------------- T2 G(e)
W("## T2 — Instrument calibration on SOURCE audio only (Q5 §3, §9)\n")
W("| encoder | G(e) = usable range | tier bound 0.10·G | 1-sample-shift response | scale response | F2 |")
W("|---|---|---|---|---|---|")
for e in ENC:
    g = cal.get("calibration", {}).get(e, {}).get("G")
    f2 = fuzz.get("F2", {}).get("encoders", {}).get(e, {})
    f1 = fuzz.get("F1", {}).get("encoders", {}).get(e, {}).get("recorded", {})
    sc = max(f1.get("scale_0p5", 0), f1.get("scale_2p0", 0))
    W("| `%s` | %.4f | %.4f | %.3g | %.3g | **%s** |"
      % (e, g, 0.10 * g, f1.get("shift1"), sc, f2.get("verdict")))
W("")

# ---------------------------------------------------------------- T3 ceiling/floor
W("## T3 — Human within-speaker ceiling and between-speaker floor, source audio (Q5 §3)\n")
W("| encoder | set | ceiling C̃ range over states | floor F_hi range | separability gate |")
W("|---|---|---|---|---|")
for e in ENC:
    for S in ("S", "L"):
        blk = cal["calibration"][e]["sets"][S]["states"]
        cw = [v["C_within"]["median"] for v in blk.values() if "C_within" in v]
        fh = [v["F_src"]["p95"] for v in blk.values() if "F_src" in v]
        gp = sum(1 for v in blk.values() if (v.get("gate") or {}).get("pass"))
        W("| `%s` | %s | %.3f – %.3f | %.3f – %.3f | %d/%d PASS |"
          % (e, S, min(cw), max(cw), min(fh), max(fh), gp, len(blk)))
W("")

# ---------------------------------------------------------------- T4 retention
W("## T4 — Speaker-embedding retention, Set S, all six states pooled\n")
W("⛔ Cosine values are ENCODER-SPECIFIC and are never averaged across encoders.\n")
W("| arm | `ecapa` | `redimnet_M_vb2_ptn` | `redimnet_b6_lm` | spread |")
W("|---|---|---|---|---|")
rows = []
for a in arms:
    v = {e: q5["arms"][a][e]["sets"]["S"]["CROSS"]["R"] for e in ENC}
    med = {e: v[e]["median"] for e in ENC}
    rows.append((med["ecapa"], a, v, med))
for _k, a, v, med in sorted(rows, reverse=True):
    W("| `%s` | %.4f [%.4f, %.4f] | %.4f [%.4f, %.4f] | %.4f [%.4f, %.4f] | %.4f |"
      % (a, v["ecapa"]["median"], v["ecapa"]["lo"], v["ecapa"]["hi"],
         v["redimnet_M_vb2_ptn"]["median"], v["redimnet_M_vb2_ptn"]["lo"],
         v["redimnet_M_vb2_ptn"]["hi"], v["redimnet_b6_lm"]["median"],
         v["redimnet_b6_lm"]["lo"], v["redimnet_b6_lm"]["hi"],
         max(med.values()) - min(med.values())))
W("")

# ---------------------------------------------------------------- T5 labels
W("## T5 — Q5 identity labels, 540 strata (18 arms × 3 encoders × 2 sets × strata)\n")
lab = collections.Counter()
for a, per in q5["arms"].items():
    for e, blk in per.items():
        for S, sb in blk["sets"].items():
            for st, v in sb.items():
                lab[v["label"]] += 1
W("| label | count |")
W("|---|---|")
for k, n in lab.most_common():
    W("| %s | **%d** |" % (k, n))
W("| **total** | **%d** |" % sum(lab.values()))
W("")
ag = collections.Counter(v["agreement"] for v in q5["encoder_agreement"].values())
diss = collections.Counter()
for v in q5["encoder_agreement"].values():
    for d in v["dissenters"]:
        diss[d] += 1
W("**Encoder agreement over %d (arm × set × stratum) comparisons:** %s. "
  "Dissent counts: %s.\n"
  % (len(q5["encoder_agreement"]),
     " · ".join("%s %d" % (k, n) for k, n in sorted(ag.items())),
     " · ".join("`%s` %d" % (k, n) for k, n in diss.most_common())))

# ---------------------------------------------------------------- T6 streaming
W("## T6 — Streaming identity detector (Q5 §7). Within-arm; never a ranking\n")
W("`S1` = cos(offline, streamed) on the same recording. "
  "`S2` = retention(streamed) − retention(offline), paired.\n")
W("| arm | S1 `ecapa` | S2 `ecapa` | S1 `redimnet_M_vb2_ptn` | S2 `redimnet_M_vb2_ptn` | n paired |")
W("|---|---|---|---|---|---|")
sd = q5["streaming_detector"]
srt = []
for a, per in sd.items():
    v = per["ecapa"]
    srt.append((v["S2_retention_delta_median"] if v["S2_retention_delta_median"]
                is not None else -99, a, per))
for _k, a, per in sorted(srt, reverse=True):
    e1, e2 = per["ecapa"], per["redimnet_M_vb2_ptn"]
    if e1["S1_offline_vs_streamed_median"] is None:
        W("| `%s` | — | — | — | — | **NOT MEASURED — no streamed output** |" % a)
        continue
    W("| `%s` | %.4f | %+.4f | %.4f | %+.4f | %d |"
      % (a, e1["S1_offline_vs_streamed_median"], e1["S2_retention_delta_median"],
         e2["S1_offline_vs_streamed_median"], e2["S2_retention_delta_median"],
         e1["n_paired"]))
W("")

# ---------------------------------------------------------------- T7 admissibility
W("## T7 — Measurement volume and admissibility\n")
ev = man.get("freezes", {}).get("q5_evidence", {})
W("| quantity | value |")
W("|---|---|")
W("| Q5 measurement rows | %s |" % ev.get("Q5_CELLS.jsonl", {}).get("rows"))
W("| speaker embeddings retained | %s |" % ev.get("Q5_EMBEDDINGS.npz", {}).get("arrays"))
W("| offline cells per arm | 1,736 (Set S 1,302 · Set L 210 · ladder 224) |")
W("| distinct source recordings | %s |" % man["corpus"]["counts"]["distinct_recordings"])
W("| speakers | 7 (English, one studio, one chain) |")
W("| Q5 labels | %d |" % sum(lab.values()))
W("| cross-state pair counts, reference = estimator | Set S 97,650 · Set L 1,470 |")
W("")

# ---------------------------------------------------------------- T-Q9
g4 = j("GATE4_RESULTS.json")
mv = g4.get("metric_validity", {})
W("## T-Q9 — The metric-validity instrument (Gate 4 §5, Route B)\n")
W("**Pre-registered consequence, written before any quality number existed:** "
  "%s\n" % mv.get("preregistered_consequence", "?").strip('"'))
W("**Verdict:** %s\n" % mv.get("VERDICT", "?"))
tab = mv.get("per_state") or mv.get("table") or {}
if tab:
    armsB = sorted({a for st in tab.values() for a in st})
    W("| state | " + " | ".join("`%s`" % a for a in armsB) + " |")
    W("|---" * (len(armsB) + 1) + "|")
    for st, row in tab.items():
        cells = []
        for a in armsB:
            v = row.get(a)
            cells.append("—" if v is None else ("**%.1f**" % v if v == min(
                x for x in row.values() if x is not None) else "%.1f" % v))
        W("| %s | %s |" % (st, " | ".join(cells)))
else:
    W("_Per-state values are in `GATE4_STAGE2_TABLES.md` §4, generated from the "
      "same artifact._")
W("")
W("**Gate 4 pairwise verdicts (108 within-route pairs):** %s\n"
  % json.dumps(g4.get("headline", {}))[:400])

open(OUT, "w", encoding="utf-8").write("\n".join(L) + "\n")
print("wrote %s (%d lines)" % (OUT, len(L)))
