r"""SPEC S10 — THE EVIDENCE PACKAGE IS GENERATED, NOT TYPED.

Emits sections 4, 5, 6 and 9 of GATE4_STAGE2_EVIDENCE.md directly from
GATE4_RESULTS.json. Hand-transcription is how revision 2 shipped:

  * a headline Q9 table of PRE-M2 flat medians - the very defect M2 declared
    repaired - with only 2 of 18 cells matching the shipped bootstrap median;
  * a streamed-coverage count (264 of 23 568) that reproduced under no
    definition;
  * "18 of 20 involve FocalCodec" (measured 20), "nine rest on fewer than 6"
    (ten), "loses by 104-214" (105.9-217.2), "at least three do not clear on
    the interval" (measured 8), "every other streaming arm 105-225%" (mimi_q32
    is 104.62%).

Every number below is read from the artifact. Prose that INTERPRETS a number is
written by hand in the package; the number itself is not.

    python gate4_report.py            # print to stdout
    python gate4_report.py --write    # write GATE4_STAGE2_TABLES.md
"""
import argparse
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "GATE4_RESULTS.json")
OUT = os.path.join(HERE, "GATE4_STAGE2_TABLES.md")
STATES = ("Neutral", "Angry", "Happy", "Scared", "Shouting", "Whisper")


def f(x, n=1):
    return "—" if x is None else ("%.*f" % (n, x))


def streaming(R, L):
    """SPEC S9 + S10.1: read the streaming totals FROM THE ARTIFACT.

    ⛔ BLOCKING B1 (audit 3). This function used to re-open
    results/gate4_stage2_*.jsonl and compute section 9 itself, so eighteen arms
    x three figures plus three totals were published from OUTSIDE the artifact -
    which S10.1 forbids and S9.1 defines as a defect. The numbers were right;
    the provenance was not. They are now computed once in
    `gate4_metrics.aggregate()` and only READ here.
    """
    sd = R.get("streaming_detector")
    if not sd or not sd.get("per_arm"):
        raise SystemExit(
            "SPEC S9 VIOLATION: GATE4_RESULTS.json carries no "
            "`streaming_detector` block. Re-run `gate4_metrics.py --aggregate`. "
            "This report will NOT compute section 9 from raw cells.")
    rows = sd["per_arm"]
    tot = sd["totals"]["n_streamed_cells_produced"]
    g8 = sd["totals"]["n_streamed_gate8_pass"]
    sup = sd["totals"]["n_streamed_in_support_vs_source"]
    L.append("### Q1 — streaming cost, within arm (DETECTOR, never a ranking)")
    L.append("")
    L.append("| arm | n Q1 | median rel. err | max rel. err |")
    L.append("|---|---|---|---|")
    for arm in sorted(rows, key=lambda a: (rows[a]["median_rel_pct"] is None,
                                           rows[a]["median_rel_pct"] or 0)):
        v = rows[arm]
        L.append("| `%s` | %d | %s | %s |"
                 % (arm, v["n_q1"],
                    "NO STREAMED OUTPUT" if v["median_rel_pct"] is None
                    else "**%.2f %%**" % v["median_rel_pct"],
                    f(v["max_rel_pct"], 2) if v["max_rel_pct"] else "—"))
    L.append("")
    L.append("**Streamed cells produced: %d. §8 PASS: %d. Inside the validated "
             "support domain against the SOURCE: %d (%.2f %% of those that "
             "passed §8).**"
             % (tot, g8, sup,
                sd["totals"]["pct_in_support_of_gate8_pass"] or 0.0))
    L.append("")
    L.append("⚠️ This blocks no preregistered ranking — rankings are computed on "
             "**offline** cells, and Q1 is measured against the arm's own "
             "full-context decode and needs no support domain. A streamed-vs-"
             "**source** quality claim is `NOT ESTABLISHED` for every arm.")
    L.append("")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    R = json.load(open(RES, encoding="utf-8"))
    P, cov = R["pairs"], R["support_coverage"]
    L = []

    L.append("# GATE 4 STAGE 2 — GENERATED TABLES")
    L.append("")
    L.append("⛔ **MACHINE-GENERATED BY `gate4_report.py` FROM "
             "`GATE4_RESULTS.json` (SPEC S10). DO NOT HAND-EDIT.**")
    L.append("")
    L.append("Artifact generated `%s`. Spec `%s` sha256 `%s`."
             % (R["generated_utc"], R["stage2_spec"]["file"],
                R["stage2_spec"]["sha256"][:16]))
    L.append("")

    # ---------------------------------------------------------------- 4. Q9
    mv = R["metric_validity"]
    L.append("## §4 — Q9, THE METRIC-VALIDITY INSTRUMENT")
    L.append("")
    L.append("**%s**" % mv["VERDICT"])
    L.append("")
    L.append("%s" % mv["measured"])
    L.append("")
    arms = [k for k in next(iter(mv["per_state_median_mcd"].values()))]
    arms = ["griffinlim"] + sorted(x for x in arms if x != "griffinlim")
    L.append("| state | " + " | ".join("`%s`" % x for x in arms) + " |")
    L.append("|" + "---|" * (len(arms) + 1))
    for st in STATES:
        row = mv["per_state_median_mcd"].get(st)
        if not row:
            continue
        best = min((v for v in row.values() if v is not None), default=None)
        cells = []
        for x in arms:
            v = row.get(x)
            cells.append("**%s**" % f(v) if v is not None and v == best else f(v))
        L.append("| %s | %s |" % (st, " | ".join(cells)))
    L.append("")
    L.append("⭐ **These are the §11.2.3 HIERARCHICAL estimates (SPEC S8.3).** "
             "Revision 2's table printed the pre-M2 flat medians — the defect "
             "M2 declared repaired, presented as the result.")
    L.append("")
    L.append("**Scope:** %s" % mv["scope_limit"])
    L.append("")

    # ------------------------------------------------------- 5. coverage
    L.append("## §5 — SUPPORT COVERAGE AND DETERMINISM, EVERY ARM")
    L.append("")
    L.append("| arm | route | cells | rankable | coverage | determinism | "
             "Stage 1 reproduction |")
    L.append("|---|---|---|---|---|---|---|")
    retro = (R.get("retro_sha_check") or {}).get("per_arm", {})
    for arm, c in sorted(cov.items(),
                         key=lambda kv: (kv[1]["route"],
                                         -(kv[1]["coverage_pct"] or 0))):
        rt = retro.get(arm, {})
        L.append("| `%s` | %s | %d | %d | %s**%.1f %%** | %s | %s |"
                 % (arm, c["route"], c["n_cells"], c["n_rankable"],
                    "⛔ " if (c["coverage_pct"] or 0) < 5.0 else "",
                    c["coverage_pct"],
                    c["determinism"].replace("DETERMINISM ", ""),
                    "%s %s/%s" % (rt.get("verdict", "—").replace("SHA-256 ", ""),
                                  rt.get("n_match", "—"),
                                  rt.get("n_probes", "—"))))
    L.append("")

    # ---------------------------------------------------------- 6. pairs
    from collections import Counter
    L.append("## §6 — THE PAIRWISE RESULT, %d PAIRS, WITHIN ROUTE ONLY"
             % len(P))
    L.append("")
    L.append("| verdict | pairs |")
    L.append("|---|---|")
    for v, n in Counter(p["verdict"] for p in P.values()).most_common():
        L.append("| %s | **%d** |" % (v, n))
    L.append("")
    nod = sum(1 for p in P.values()
              if "no paired admissible" in (p.get("why") or ""))
    ndg = sum(1 for p in P.values() if p.get("degenerate_interval"))
    nfoc = sum(1 for k, p in P.items()
               if p["verdict"] == "QUALITY COMPARISON NOT ESTABLISHED"
               and any("focalcodec" in x for x in k.split("|")))
    nq = sum(1 for p in P.values()
             if p["verdict"] == "QUALITY COMPARISON NOT ESTABLISHED")
    L.append("The %d refused pairs split **%d with no paired admissible cell** "
             "and **%d refused for a degenerate interval** (S5.2). **%d of the "
             "%d involve FocalCodec.**" % (nq, nod, ndg, nfoc, nq))
    L.append("")

    cap = R["power_and_coverage_caveats"]
    for label in ("ROBUST", "FLOOR_FRAGILE"):
        ks = cap[label]["pairs"]
        L.append("### §6.1 %s — %d pair%s"
                 % (label, len(ks), "" if len(ks) == 1 else "s"))
        L.append("")
        if not ks:
            L.append("*(none)*")
            L.append("")
            continue
        L.append("| pair | n cells | n rec | Δ`mcd` | 95 % CI | floor | "
                 "floor_hi | interval margin | better |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for k in ks:
            p = P[k]
            d = p["paired_diff"]
            L.append("| `%s` | %d | %d | %s | [%s, %s] | %s | %s | **%s** | `%s` |"
                     % (k.replace("|", "｜"), p["n_paired"], d["n_recordings"],
                        f(d["median"], 2), f(d["ci_lo"], 2), f(d["ci_hi"], 2),
                        f(p["floor_used_absolute"], 2), f(p.get("floor_hi"), 2),
                        f(p.get("floor_margin_interval"), 2), p["better"]))
        L.append("")
        if label == "FLOOR_FRAGILE":
            for k in ks:
                L.append("- `%s` — %s" % (k.replace("|", "｜"),
                                          cap[label]["reasons"][k]))
            L.append("")

    # per-state breakdown for every well-powered pair (S9)
    wp = sorted(cap["ROBUST"]["pairs"] + cap["FLOOR_FRAGILE"]["pairs"])
    if wp:
        L.append("### §6.2 Per-state evidence for the well-powered pairs (S9)")
        L.append("")
        L.append("Margin = |interval bound nearest zero| − that state's own "
                 "absolute floor. **Negative means that state's interval does "
                 "not clear its own floor.**")
        L.append("")
        L.append("| pair | " + " | ".join(STATES) + " |")
        L.append("|" + "---|" * (len(STATES) + 1))
        for k in wp:
            ps = P[k].get("per_state") or {}
            cells = []
            for st in STATES:
                v = ps.get(st) or {}
                if v.get("interval_margin") is None:
                    cells.append("—")
                else:
                    # ⚠️ audit-3 MINOR: `n=` used to print CELLS while reading
                    # as independent points. Both are shown: cells / clusters.
                    cells.append("%s%+.2f<br>%d cells<br>%d rec%s"
                                 % ("" if v["interval_clears_state_floor"]
                                    else "⛔ ", v["interval_margin"],
                                    v["n_cells"], v["n_recordings"],
                                    " ⛔deg" if v.get("degenerate") else ""))
            L.append("| `%s` | %s |" % (k.replace("|", "｜"), " | ".join(cells)))
        L.append("")

    thin = cap["THIN_OR_SELECTION_CONDITIONED"]
    tk = thin["pairs"]
    if tk:
        ns = [P[k]["n_paired"] for k in tk]
        nr = [P[k]["paired_diff"]["n_recordings"] for k in tk]
        same = sum(1 for k in tk
                   if P[k]["n_paired"] == P[k]["paired_diff"]["n_recordings"])
        mags = [abs(P[k]["paired_diff"]["median"]) for k in tk]
        nfocal = sum(1 for k in tk if any("focalcodec" in x
                                          for x in k.split("|")))
        L.append("### §6.3 THIN / SELECTION-CONDITIONED — %d pairs" % len(tk))
        L.append("")
        L.append("**%d to %d paired cells** out of 1 736, carried by **%d to %d "
                 "independent recordings**. **%d of %d contain a FocalCodec "
                 "arm.** Effect magnitudes **%.1f to %.1f**. **%d rest on fewer "
                 "than 6 paired cells.**"
                 % (min(ns), max(ns), min(nr), max(nr), nfocal, len(tk),
                    min(mags), max(mags), sum(1 for n in ns if n < 6)))
        L.append("")
        L.append("⚠️ **Cells are not clusters.** `n_recordings == n_cells` for "
                 "only **%d of %d** of these pairs; the other %d carry ladder "
                 "rungs that collapse into one recording, so they hold **fewer "
                 "independent points than cells**."
                 % (same, len(tk), len(tk) - same))
        L.append("")
        L.append("⭐ **%s**" % thin["direction_of_bias"])
        L.append("")

    nclear = sum(1 for p in P.values()
                 if p["verdict"].startswith("SEPARATION")
                 and p.get("interval_also_clears_floor") is False)
    L.append("**Of the %d established pairs, %d do NOT clear the floor on the "
             "interval** (the frozen rule tests the point estimate; SPEC S6)."
             % (sum(1 for p in P.values() if p["verdict"].startswith("SEPARATION")),
                nclear))
    L.append("")

    # ------------------------------------------------------- 9. streaming
    L.append("## §9 — THE STREAMING DETECTOR")
    L.append("")
    streaming(R, L)

    # ------------------------------------- 10. scale + aggregation deviation
    ms = R.get("metric_scale") or {}
    ad = R.get("aggregation_deviation_summary") or {}
    L.append("## §10 — THE SCALE OF `mcd`, AND THE M2 AGGREGATION DEVIATION")
    L.append("")
    L.append("⛔ **These `mcd` values are NOT literature-scale MCD.** %s. "
             "**Measured range across all %d arm × state estimates: "
             "%s to %s.** %s"
             % (ms.get("construction", "—"), ms.get("n_estimates", 0),
                f(ms.get("min"), 2), f(ms.get("max"), 2),
                ms.get("⛔ never", "")))
    L.append("")
    L.append("**M2 aggregation deviation** — |S3 hierarchical estimate| − |flat "
             "median over cells|, across %d pairs: **median %s, max %s**. "
             "Pairs whose floor test flips: **%d**%s."
             % (ad.get("n_pairs", 0), f(ad.get("median_abs_shift"), 4),
                f(ad.get("max_abs_shift"), 4),
                len(ad.get("pairs_whose_floor_test_flips") or []),
                (" (`%s`)" % "`, `".join(
                    x.replace("|", "｜")
                    for x in ad["pairs_whose_floor_test_flips"]))
                if ad.get("pairs_whose_floor_test_flips") else ""))
    L.append("")
    L.append("⚠️ Revisions 3 and 4 printed **1.20** for that median. That figure "
             "was measured under the OLD `(speaker, index, rung_s)` recording "
             "key and was never recomputed after MAJOR-1 repaired it.")
    L.append("")

    txt = "\n".join(L)
    if a.write:
        open(OUT, "w", encoding="utf-8").write(txt + "\n")
        print("wrote", OUT)
    else:
        print(txt)
    return 0


if __name__ == "__main__":
    sys.exit(main())
