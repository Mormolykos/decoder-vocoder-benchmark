r"""Q5 reporting — every table is GENERATED from the artifacts, never typed.

Reads Q5_CALIBRATION.json, Q5_FUZZ.json and (when it exists) Q5_RESULTS.json;
writes Q5_TABLES.md. Refuses to render a results section that is not there, and
refuses to print a label for an encoder the fuzz removed or demoted.

  --write   write Q5_TABLES.md
  (default) print to stdout
"""
from __future__ import annotations

import argparse
import json
import os

import q5_lib as Q

CAL = os.path.join(Q.HERE, "Q5_CALIBRATION.json")
FUZZ = os.path.join(Q.HERE, "Q5_FUZZ.json")
RES = os.path.join(Q.HERE, "Q5_RESULTS.json")
OUT = os.path.join(Q.HERE, "Q5_TABLES.md")


def f(x, n=4):
    return "—" if x is None else ("%.*f" % (n, x))


def ci(o):
    if not o:
        return "—"
    if "lo" not in o:
        return "REFUSED: %s" % o.get("refused", "?")
    return "%s [%s, %s] n=%s" % (f(o["median"]), f(o["lo"]), f(o["hi"]),
                                 o.get("n_recordings"))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    L = []
    W = L.append

    W("# Q5 — SPEAKER IDENTITY. GENERATED TABLES.\n")
    W("Generated by `q5_report.py` from the artifacts named in each section. "
      "⛔ No number here is typed by hand.\n")

    if not os.path.isfile(FUZZ) or not os.path.isfile(CAL):
        W("⛔ **NOT RENDERABLE.** `Q5_FUZZ.json` and `Q5_CALIBRATION.json` must "
          "both exist (SECTION 9.0 steps 1–3).\n")
        print("\n".join(L))
        return 1

    fz = json.load(open(FUZZ, encoding="utf-8"))
    cal = json.load(open(CAL, encoding="utf-8"))
    spec = cal["spec"]
    W("Spec `Q5_SPEC.md` **%s** (revision %d), frozen %s.\n"
      % (spec["spec_sha256"][:16], spec["revisions"], spec["spec_frozen_utc"]))

    W("## 1. The panel as actually loaded\n")
    W("| encoder | params source | training corpus | device | checkpoint sha256 |")
    W("|---|---|---|---|---|")
    for n, m in cal["panel"].items():
        W("| `%s` | %s | %s | %s | `%s` |"
          % (n, m["source"], m["training_corpus"], m["device"],
             m["checkpoint_sha256"][:16]))
    W("")

    W("## 2. F1 — metric mechanics (SECTION 9.1)\n")
    W("| encoder | verdict | identity cos min | max_abs_err | cold start | shift1 | scale |")
    W("|---|---|---|---|---|---|---|")
    for n, r in fz["F1"]["encoders"].items():
        p = r["probes"]
        W("| `%s` | **%s** | %s | %s | %s | %s | %s |"
          % (n, r["verdict"], f(p["identity"]["cos_min"], 9),
             p["identity"]["max_abs_err_max"],
             "PASS" if p["cold_start"]["pass"] else "FAIL",
             f(r["recorded"]["shift1"], 6),
             f(max(r["recorded"]["scale_0p5"], r["recorded"]["scale_2p0"]), 6)))
    W("")

    W("## 3. Ceiling, floor and the separability gate (SECTION 3, SECTION 9.2), source only\n")
    for e, blk in cal["calibration"].items():
        W("**`%s`** — G(e) = **%s**\n" % (e, f(blk["G"])))
        W("| set | stratum | C_within (ceiling) | F_src median | F_hi (p95) | gate C.lo > F_hi |")
        W("|---|---|---|---|---|---|")
        for S, sb in blk["sets"].items():
            for st, v in sb["states"].items():
                if "C_within" not in v:
                    W("| %s | %s | REFUSED: %s | — | — | — |"
                      % (S, st, v.get("refused", "?")))
                    continue
                g = v.get("gate") or {}
                W("| %s | %s | %s | %s | %s | %s |"
                  % (S, st, ci(v["C_within"]), f((v["F_src"] or {}).get("median")),
                     f((v["F_src"] or {}).get("p95")),
                     "PASS" if g.get("pass") else "**FAIL**"))
            cr = (sb.get("cross") or {}).get("C_cross")
            if cr:
                W("| %s | CROSS | %s | — | — | — |" % (S, ci(cr)))
        W("")

    W("## 4. F2 — calibrated tier gates (SECTION 9.3)\n")
    W("| encoder | G(e) | bound 0.10×G | shift1 | scale | verdict |")
    W("|---|---|---|---|---|---|")
    for n, r in fz.get("F2", {}).get("encoders", {}).items():
        t = (r.get("gates") or {}).get("tier_test") or {}
        s = (r.get("gates") or {}).get("scale_invariance") or {}
        W("| `%s` | %s | %s | %s | %s | **%s** |"
          % (n, f(r.get("G")), f(r.get("bound"), 6), f(t.get("shift1"), 6),
             f(s.get("scale_response"), 6), r.get("verdict")))
    W("")

    if not os.path.isfile(RES):
        W("## 5. Offline results\n")
        W("⛔ **NOT RUN.** `Q5_RESULTS.json` does not exist. Steps 4–6 of "
          "SECTION 9.0 have not been executed, and nothing is inferred about them.\n")
    else:
        res = json.load(open(RES, encoding="utf-8"))
        W("## 5. HOW TO READ THESE NUMBERS — the scope of the claim\n")
        W("**`R` is cosine between the source and its reconstruction in ONE speaker "
          "encoder's embedding space.** It is a measurement of **speaker-embedding "
          "retention** and of nothing else.\n")
        W("⛔ It is **not** perceptual quality, **not** intelligibility, **not** a "
          "statement that an arm is a good decoder, and **not** comparable across "
          "encoders as a raw magnitude. An arm may retain the representation almost "
          "perfectly while sounding poor: retention and perceptual quality are "
          "different axes, and `griffinlim` — a zero-parameter phase-retrieval "
          "algorithm, and the arm GATE4_PREREG.md §5 Q9 installed as the validity "
          "floor — has the **highest speaker-embedding retention of the eighteen**. "
          "⛔ That sentence is the whole claim. It does not make it the best decoder, "
          "and Q9 exists precisely because that arm also tops `mcd`, a quantity it "
          "effectively optimises.\n")
        W("**`mcd` remains Gate 4's only ranking metric. Q5 ranks nothing.**\n")
        W("## 5.1 Labels per arm × encoder × set × stratum (SECTION 8)\n")
        W("| arm | encoder | set | stratum | R | D | C | F_hi | label | reason |")
        W("|---|---|---|---|---|---|---|---|---|---|")
        for arm, per in res["arms"].items():
            for e, blk in per.items():
                for S, sb in blk["sets"].items():
                    for st, v in sb.items():
                        W("| `%s` | `%s` | %s | %s | %s | %s | %s | %s | **%s**%s | %s |"
                          % (arm, e, S, st, ci(v["R"]), ci(v["D"]), ci(v["C"]),
                             f(v["F_hi"]), v["label"],
                             "" if not v["marker"] else " · " + v["marker"],
                             v["label_reason"]))
        W("")
        W("## 5.2 The same aggregates stratified by support (SECTION 4)\n")
        W("⛔ **The support state is a COVARIATE, never an exclusion.** It records "
          "what Stage 2 found about `mcd`'s validated domain, which is a statement "
          "about `mcd`, not about a speaker encoder. Labels in §5.1 are computed on "
          "**all** admissible cells; the rows below are the same quantities split by "
          "that covariate and **carry no label**. A cosine computed on a collapsed or "
          "band-limited reconstruction is a real measurement of what the encoder sees "
          "and is **not** evidence that the arm is a functioning decoder.\n")
        W("| arm | encoder | set | stratum | support | n | R | D |")
        W("|---|---|---|---|---|---|---|---|")
        for arm, per in res["arms"].items():
            for e, blk in per.items():
                for S, sb in blk["sets"].items():
                    for st, v in sb.items():
                        for sup, sv in (v.get("by_support") or {}).items():
                            W("| `%s` | `%s` | %s | %s | %s | %d | %s | %s |"
                              % (arm, e, S, st, sup, sv["n"], ci(sv["R"]), ci(sv["D"])))
        W("")
        W("## 5.3 Duration (SECTION 6) — which rungs may be compared across arms\n")
        d = res.get("duration", {})
        W("- **1 s is INADMISSIBLE everywhere** under the frozen 2.00 s minimum.")
        W("- **2 s is admissible in 11 arms and inadmissible in 7**, because realised "
          "reconstruction length at that nominal rung spans 1.9199–2.0434 s and the "
          "threshold cuts through it. ⛔ **It is therefore excluded from CROSS-ARM "
          "comparison** — the surviving arms are selected by their own output-length "
          "behaviour — **but it is reported per arm wherever it is admissible**, and "
          "those values are in the table below.")
        W("- ⛔ The 2.00 s threshold is **not relaxed** to rescue that rung.")
        W("- **Cross-arm duration comparison uses %s.**\n"
          % " / ".join("%g s" % x for x in d.get("cross_arm_rungs", [])))
        W("| arm | encoder | rung | cross-arm comparable | n measured | texts | R |")
        W("|---|---|---|---|---|---|---|")
        for arm, per in d.get("arms", {}).items():
            for e, rungs in per.items():
                for rung, v in rungs.items():
                    W("| `%s` | `%s` | %s | %s | %d | %d | %s |"
                      % (arm, e, rung, "yes" if v["cross_arm_comparable"] else "**no**",
                         v["n_measured"], v["n_texts"], ci(v["R"])))
        W("")
        W("## 6. Streaming detector (SECTION 7) — never a ranking\n")
        W("| arm | encoder | S1 offline↔streamed | S2 retention delta | n paired | NOT MEASURED |")
        W("|---|---|---|---|---|---|")
        for arm, per in res["streaming_detector"].items():
            for e, v in per.items():
                W("| `%s` | `%s` | %s | %s | %s | %s |"
                  % (arm, e, f(v["S1_offline_vs_streamed_median"]),
                     f(v["S2_retention_delta_median"]), v["n_paired"],
                     v["n_not_measured"]))
        W("")
        W("## 7. Encoder agreement (SECTION 8.6) — reported, never resolved\n")
        W("| arm · set · stratum | agreement | dissenters | labels |")
        W("|---|---|---|---|")
        for k, v in res["encoder_agreement"].items():
            W("| %s | %s | %s | %s |"
              % (k, v["agreement"], ", ".join(v["dissenters"]) or "—",
                 "; ".join("%s=%s" % (a, b) for a, b in v["labels"].items())))
        W("")

    txt = "\n".join(L) + "\n"
    if a.write:
        open(OUT, "w", encoding="utf-8").write(txt)
        print("wrote %s (%d lines)" % (os.path.basename(OUT), len(L)))
    else:
        print(txt)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
